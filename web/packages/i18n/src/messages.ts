/**
 * The core message dictionary — the copy every build carries.
 *
 * The en entries are the schema for this file; `messages.zh.ts` has to cover
 * the same keys, and `Record<CoreMessageKey, string>` is what enforces that.
 *
 * # What belongs here
 *
 * Membership is decided by consumers, not by subject: a key lives here when
 * something in `packages/` — the shared components and the two gateway feature
 * packages — or the admin app renders it. Copy that only a hosted deployment
 * can ever show (sign-up, organization members, wallets, payments, compliance
 * exports) lives in the dictionary of the app that renders it and is merged in
 * at start-up via `registerMessages`.
 *
 * Keeping those out is not housekeeping. This package is part of the published
 * source, so every entry that stays here is copy a self-hosted operator
 * downloads, ships, and can never reach — and there is nothing in a dictionary
 * that says which of its entries have a renderer. `deploy/scripts/check-i18n-dictionaries.py`
 * answers that: every key must appear as an identifier somewhere outside the
 * dictionary files, or the gate names it (ADR-0206).
 *
 * The zh half is loaded on demand: a session only ever uses one language, so
 * shipping both in the first payload hands every reader a dictionary they will
 * never open.
 */
